"""
prompts.py
定義五級「討人厭程度」準則，並提供 build_prompt() 給主程式呼叫。
"""

# 五級定義（模型可學的用語）
LEVEL_DEFS = {
    1: "平穩中性、無情緒起伏、短句為主、不含反諷與質疑、不評斷對方。",
    2: "輕微敷衍、淡淡的不耐或推託感，可用少量口語語氣詞，但避免明顯諷刺與指責。",
    3: "帶明顯不悅或被動攻擊，允許輕度反諷或質疑，點出對方行為問題，但不使用貶抑詞彙。",
    4: "冷酸／高階反諷：語氣冷靜、理性、流暢；表面像在稱讚或評論，實際暗藏諷刺；禮貌外表下帶冷刺。",
    5: "極端酸／高段嘲諷：語氣尖銳、直接且聰明；帶強烈嘲諷與壓迫感，結合幽默反差；聽起來像玩笑但實際很刺。",
}

LEVELS = [1, 2, 3, 4, 5]


def build_prompt(scenario: str, level: int, max_chars: int = 60) -> str:
    """回傳一段完整 prompt，內含五級準則與目標等級，主程式只需提供情境與等級。"""
    rules = "\n".join([f"- Level {k}: {v}" for k, v in LEVEL_DEFS.items()])
    return f"""你是一個「語氣模擬生成器」，要模擬人類在不同情境下的回覆語氣。
請依下列五級準則生成一句自然中文回覆（限制在 {max_chars} 字以內），不可輸出解釋。

五級準則：
{rules}

一般規則：
- 僅輸出句子本體，不要任何多餘說明。
- 不使用表情符號、括號內舞台指示或顏文字。
- 不使用粗話或人身攻擊，不得提及 AI/系統/生成。
- 語氣要像真實人講話，且等級差異明確。

情境：{scenario}
目標等級：Level {level}
輸出："""

def build_prompt(original_text: str, level: int, max_chars: int = 60) -> str:
    target_desc = LEVEL_DEFS.get(level, LEVEL_DEFS[2])
    examples = FEW_SHOT_EXAMPLES.get(level, [])
    examples_str = "\n".join(examples)

    return f"""你是一位精通漢語的「聊天語氣改寫專家」。
請將使用者的「原句」改寫為符合「Level {level}」的語氣。

### 目標語氣與態度：
{target_desc}

### 風格參考（請學習其邏輯）：
{examples_str}

### 嚴格執行規則：
1. **保留原意**：**絕對不要回答問題**。如果原句是問句，改寫後也要是問句（或反問）。
2. **視角固定**：保持原句的人稱視角。
3. **多樣性**：不要死板重複範例中的詞彙，請依情境自然改寫。
4. **長度限制**：{max_chars} 字以內。
5. **只輸出改寫句子**：不要加任何解釋、不要加「Level X：」。

### 開始改寫：
原句："{original_text}"
Level {level} 改寫："""

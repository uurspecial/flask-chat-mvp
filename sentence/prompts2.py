
# 五級定義（模型可學的語氣描述）
LEVEL_DEFS = {
    1: "平穩中性、無情緒起伏、短句為主、不含反諷與質疑、不評斷對方。",
    2: "輕微敷衍、淡淡的不耐或推託感，可用少量口語語氣詞，但避免明顯諷刺與指責。",
    3: "帶明顯不悅或被動攻擊，允許輕度反諷或質疑，點出對方行為問題，但不使用貶抑詞彙。",
    4: "明顯尖銳與挑釁，強烈不滿或諷刺，直接點出對方行為造成的問題或負擔，語氣壓迫但不失控。",
    5: "強烈反諷與輕蔑，直接否定對方做法或結果，語勢逼人、毫不留情，但不使用粗話與侮辱字眼。",
}

LEVELS = [1, 2, 3, 4, 5]


def build_prompt(sentence: str, level: int, max_chars: int = 60) -> str:
    """回傳完整的改寫任務 prompt，主程式只需給句子與等級。"""
    rules = "\n".join([f"{k}: {v}" for k, v in LEVEL_DEFS.items()])
    return f"""你是一個「語氣改寫器」。請依下列五級準則，將提供的句子改寫成符合指定等級的自然中文口語句子（限制在 {max_chars} 字以內）。
重要：保留原始語意，不新增內容，不提出問題，不給任何解釋。

五級準則：
{rules}

一般規則：
- 僅輸出改寫後的句子，不要多餘說明或前後綴。
- 不使用表情符號、括號內舞台指示或顏文字。
- 不使用粗話或人身攻擊，不得提及 AI/系統/生成。
- 語氣要像真實人講話，且等級差異明確。

原始句子：{sentence}
目標等級：Level {level}
輸出："""
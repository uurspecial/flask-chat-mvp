# 2. 定義語氣準則
# =========================
LEVEL_DEFS = {
    1: "【Level 1：溫和】(重點在對方感受，語氣柔和)",
    2: "【Level 2：中性】(陳述事實，冷靜直接)",
    3: "【Level 3：不滿】(明顯不耐煩，帶情緒壓力)",
    4: "【Level 4：酸】(反語、假稱讚、陰陽怪氣)"
}

LEVELS = [1, 2, 3, 4]

# =========================
# 3. 核心功能：Prompt 建構器 (邏輯已修正)
# =========================
def build_prompt(original_text: str, level: int) -> str:
    """
    動態組裝 Prompt。
    使用新的字典結構自動抓取「上一級」作為輸入，「本級」作為輸出。
    """
    if level not in LEVELS:
        return "Error: Level must be 1, 2, 3, or 4."

    target_desc = LEVEL_DEFS.get(level)
    level_labels = {1: "一級改寫", 2: "二級改寫", 3: "三級改寫", 4: "四級改寫"}
    current_label = level_labels[level]
    
    examples_str_list = []
    
    # === 修正重點：遍歷新的字典格式 ===
    for data in FEW_SHOT_DATASET:
        # 決定範例的「輸入句」是甚麼
        # 如果目標是 Level 1，輸入就是 original
        # 如果目標是 Level 2，輸入就是 Level 1 的句子
        if level == 1:
            ex_input = data["original"]
        else:
            ex_input = data[level - 1] # 取得上一級的句子
            
        # 決定範例的「輸出句」是甚麼
        ex_output = data[level]
        
        # 組合字串
        examples_str_list.append(f"原句：{ex_input} -> {current_label}：{ex_output}")
    
    examples_str = "\n".join(examples_str_list)

    return f"""你是一位語氣改寫專家。
請將「原句」改寫為「{current_label}」版本。

### 目標語氣：
{target_desc}

### 參考範例：
{examples_str}

### 你的任務：
原句："{original_text}"
{current_label}："""
